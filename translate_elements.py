LINE = re.compile(r'^([ \t]*)(Name|Description) = ".*";[ \t]*$')
D = "src/simulation/elements"
found = set()
updated = 0
for fn in sorted(os.listdir(D)):
    if not fn.endswith(".cpp"):
        continue
    p = os.path.join(D, fn)
    with open(p, encoding="utf-8", newline="") as f:
        text = f.read()
    m = re.search(r'Identifier = "DEFAULT_PT_([A-Z0-9_]+)";', text)
    if not m:
        continue
    code = m.group(1)
    if code not in T:
        sys.exit("В T нет ключа " + code)
    name, desc = T[code]
    if not name or not desc or any(c in name + desc for c in '"\\'):
        sys.exit("Недопустимое значение для " + code)
    lines = text.split("\n")
    hits = {"Name": 0, "Description": 0}
    for i, line in enumerate(lines):
        mm = LINE.match(line)
        if mm:
            hits[mm.group(2)] += 1
            value = name if mm.group(2) == "Name" else desc
            lines[i] = '%s%s = "%s";' % (mm.group(1), mm.group(2), value)
    if hits != {"Name": 1, "Description": 1}:
        sys.exit("В %s не по одной строке Name и Description: %s" % (fn, hits))
    new = "\n".join(lines)
    found.add(code)
    if new != text:
        with open(p, "w", encoding="utf-8", newline="") as f:
            f.write(new)
        updated += 1
        print("updated", fn)
missing = set(T) - found
if missing:
    sys.exit("Ключи из T не найдены в файлах: " + ", ".join(sorted(missing)))
print("Всего обновлено файлов:", updated)

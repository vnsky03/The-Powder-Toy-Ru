def ru_name(code, en_name):
    entry = T.get(code)
    if entry:
        return entry[0] or en_name
    return en_name

def ru_desc(code, en_desc):
    entry = T.get(code)
    if entry and entry[1]:
        return entry[1]
    return en_desc

d = "src/simulation/elements"
updated = 0
for fn in sorted(os.listdir(d)):
    if not fn.endswith(".cpp"):
        continue
    p = os.path.join(d, fn)
    txt = open(p, encoding="utf-8").read()
    m = re.search(r'Identifier = "DEFAULT_PT_([A-Z0-9_]+)";', txt)
    code = m.group(1) if m else None
    if not code or code not in T:
        continue
    orig = txt
    txt = re.sub(r'^\s*Name = "[^"]*";\s*$', 'Name = "%s";' % ru_name(code, ""), txt, count=1, flags=re.M)
    desc_line = re.search(r'^(\s*)Description = "[^"]*";\s*$', txt, re.M)
    if desc_line:
        en_desc = re.search(r'Description = "([^"]*)";', txt).group(1)
        txt = re.sub(r'^(\s*)Description = "[^"]*";\s*$', r'\1Description = "%s";' % ru_desc(code, en_desc), txt, count=1, flags=re.M)
    if txt != orig:
        open(p, "w", encoding="utf-8").write(txt)
        updated += 1
        print("updated", fn)
print("Тотал обновлений:", updated)